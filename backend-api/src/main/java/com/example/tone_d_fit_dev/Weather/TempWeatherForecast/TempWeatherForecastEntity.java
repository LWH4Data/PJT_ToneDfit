package com.example.tone_d_fit_dev.Weather.TempWeatherForecast;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Entity
@Table(name = "weather_forecast_temp")
@Getter
@Setter
@NoArgsConstructor // 기본 생성자 필수
public class TempWeatherForecastEntity {

    // 기본 키 (Primary Key) - PostgreSQL IDENTITY 매핑
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id; // INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY

    // 기온 정보
    // NUMERIC(4, 1) -> Double/Float
    private Double temperatureCurrent;     // temperature_current
    private Double temperatureMax;         // temperature_max
    private Double temperatureMin;         // temperature_min
    private Double temperatureFeelsLike;   // temperature_feels_like

    // 강수 및 기상 정보
    private String weatherCondition; // weather_condition (NOT NULL)
    private String precipitationType; // precipitation_type
    private Short precipitationChance;    // precipitation_chance (SMALLINT)
    private Double precipitationAmount;    // precipitation_amount (NUMERIC(5, 2))

    // 바람 및 습도
    private Short humidityCurrent;        // humidity_current (SMALLINT)
    private Double windSpeed;              // wind_speed (NUMERIC(4, 2))

    // 지수 정보
    private Short dustIndex;             // dust_index (SMALLINT)
    private String dustCondition;          // dust_condition
    private Short uvIndex;               // uv_index (SMALLINT)
    private String uvCondition;           // uv_condition

    // 참고: 생성자, toString() 등은 Lombok을 사용하면 @Data 또는 @Builder로 자동 생성 가능합니다.
}